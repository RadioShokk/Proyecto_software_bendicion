-- Farmacia La Bendición • MySQL 8 / MariaDB 10.6+, InnoDB, UTF-8
SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, username VARCHAR(50) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('propietaria','apoyo') NOT NULL,
 can_manage_clients TINYINT(1) NOT NULL DEFAULT 0,
 active TINYINT(1) NOT NULL DEFAULT 1, last_login DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
 business_name VARCHAR(140) NOT NULL DEFAULT 'Farmacia La Bendición',
 business_address VARCHAR(250) NOT NULL DEFAULT '',
 business_phone VARCHAR(40) NOT NULL DEFAULT '',
 expiry_alert_days INT UNSIGNED NULL,
 retention_policy VARCHAR(250) NOT NULL DEFAULT 'Pendiente de validación',
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
INSERT IGNORE INTO settings(id,business_name) VALUES(1,'Farmacia La Bendición');
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(60) NOT NULL UNIQUE, name VARCHAR(180) NOT NULL,
 description VARCHAR(500) NULL, category VARCHAR(100) NOT NULL DEFAULT '',
 requires_prescription TINYINT(1) NOT NULL DEFAULT 0,
 sale_price DECIMAL(12,2) NOT NULL DEFAULT 0.00,
 min_stock INT UNSIGNED NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_products_name(name)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS providers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(180) NOT NULL, phone VARCHAR(40) NOT NULL DEFAULT '',
 address VARCHAR(255) NOT NULL DEFAULT '', active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS clients (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(180) NOT NULL, phone VARCHAR(40) NOT NULL DEFAULT '',
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS lots (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id BIGINT UNSIGNED NOT NULL,
 lot_code VARCHAR(90) NOT NULL DEFAULT '',
 expiry_date DATE NULL,
 available_qty INT UNSIGNED NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_lot_product FOREIGN KEY(product_id) REFERENCES products(id),
 INDEX idx_lot_fefo(product_id,expiry_date,available_qty)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sales (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 receipt_no VARCHAR(30) NULL UNIQUE,
 client_id BIGINT UNSIGNED NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 subtotal DECIMAL(12,2) NOT NULL,
 total DECIMAL(12,2) NOT NULL,
 payment_method ENUM('efectivo') NOT NULL DEFAULT 'efectivo',
 cash_received DECIMAL(12,2) NOT NULL,
 cash_change DECIMAL(12,2) NOT NULL,
 request_token CHAR(32) NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_sale_client FOREIGN KEY(client_id) REFERENCES clients(id),
 CONSTRAINT fk_sale_user FOREIGN KEY(user_id) REFERENCES users(id),
 INDEX idx_sale_date(created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sale_lines (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 sale_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED NOT NULL,
 lot_id BIGINT UNSIGNED NOT NULL,
 product_name VARCHAR(180) NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 unit_price DECIMAL(12,2) NOT NULL,
 line_total DECIMAL(12,2) NOT NULL,
 CONSTRAINT fk_sl_sale FOREIGN KEY(sale_id) REFERENCES sales(id),
 CONSTRAINT fk_sl_product FOREIGN KEY(product_id) REFERENCES products(id),
 CONSTRAINT fk_sl_lot FOREIGN KEY(lot_id) REFERENCES lots(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS purchases (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 provider_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 invoice_no VARCHAR(80) NOT NULL,
 status ENUM('pendiente','recibida') NOT NULL DEFAULT 'pendiente',
 total DECIMAL(12,2) NOT NULL,
 request_token CHAR(32) NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 received_at DATETIME NULL,
 CONSTRAINT fk_pur_provider FOREIGN KEY(provider_id) REFERENCES providers(id),
 CONSTRAINT fk_pur_user FOREIGN KEY(user_id) REFERENCES users(id),
 INDEX idx_pur_date(created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS purchase_lines (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 purchase_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 lot_id BIGINT UNSIGNED NULL,
 lot_code VARCHAR(90) NOT NULL DEFAULT '',
 expiry_date DATE NULL,
 quantity INT UNSIGNED NOT NULL,
 unit_cost DECIMAL(12,2) NOT NULL,
 line_total DECIMAL(12,2) NOT NULL,
 CONSTRAINT fk_pl_purchase FOREIGN KEY(purchase_id) REFERENCES purchases(id),
 CONSTRAINT fk_pl_product FOREIGN KEY(product_id) REFERENCES products(id),
 CONSTRAINT fk_pl_lot FOREIGN KEY(lot_id) REFERENCES lots(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id BIGINT UNSIGNED NOT NULL,
 lot_id BIGINT UNSIGNED NOT NULL,
 type ENUM('compra','venta','ajuste_entrada','ajuste_salida') NOT NULL,
 quantity INT NOT NULL,
 ref_type ENUM('compra','venta','ajuste') NOT NULL,
 ref_id BIGINT UNSIGNED NOT NULL,
 note VARCHAR(255) NOT NULL DEFAULT '',
 user_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_mov_product FOREIGN KEY(product_id) REFERENCES products(id),
 CONSTRAINT fk_mov_lot FOREIGN KEY(lot_id) REFERENCES lots(id),
 CONSTRAINT fk_mov_user FOREIGN KEY(user_id) REFERENCES users(id),
 INDEX idx_mov_product_created(product_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stock_adjustments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 reason VARCHAR(255) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(product_id) REFERENCES products(id),
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NULL,
 action VARCHAR(70) NOT NULL,
 entity_type VARCHAR(50) NOT NULL,
 entity_id BIGINT UNSIGNED NULL,
 context VARCHAR(500) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id),
 INDEX idx_audit_created(created_at)
) ENGINE=InnoDB;
